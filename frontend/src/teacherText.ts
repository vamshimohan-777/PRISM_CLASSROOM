export function localisedPlanText(text: string, lang: Language): string {
  if (lang === 'en') return text;
  const gapPrefix = 'Prerequisite gap: ';
  if (text.startsWith(gapPrefix)) {
    const title = text.slice(gapPrefix.length);
    const skill = Object.values(PREREQUISITE_TEXT).find((entry) => entry.name.en === title);
    return `${TEACHER_TEXT[lang].gapBarrier} ${skill?.name[lang] ?? title}`;
  }
  const match =
    LIBRARY.find((entry) => entry.en === text) ??
    Object.values(MISCONCEPTION_LABELS).find((entry) => entry.en === text);
  if (match) return match[lang];
  const skill = Object.values(PREREQUISITE_TEXT).find((entry) => entry.remedy.en === text || entry.objective.en === text);
  if (skill) return skill.remedy.en === text ? skill.remedy[lang] : skill.objective[lang];
  return text;
}

export function prerequisiteName(id: string | undefined, lang: Language, fallback = ''): string {
  return (id && PREREQUISITE_TEXT[id]?.name[lang]) || fallback;
}

export function prerequisiteRemedy(id: string | undefined, lang: Language, fallback = ''): string {
  return (id && PREREQUISITE_TEXT[id]?.remedy[lang]) || fallback;
}

export function localisedDuration(duration: string, lang: Language): string {
  return duration.replace('min', lang === 'hi' ? 'मिनट' : lang === 'te' ? 'నిమి' : 'min');
}

export function reasonForRoute(route: string, t: TeacherStrings): string {
  const byRoute: Record<string, string> = {
    foundation: t.reasonFoundation,
    'visual-support': t.reasonVisual,
    'guided-practice': t.reasonGuided,
    extension: t.reasonExtension,
    test: t.reasonTest,
    'follow-up': t.reasonFollowUp,
  };
  return byRoute[route] ?? '';
}
